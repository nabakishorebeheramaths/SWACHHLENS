export const getStates = () => {
  return Object.keys(indiaLocations).sort();
};


export const getDistricts = (state) => {
  if (!state || !indiaLocations[state]) {
    return [];
  }

  return Object.keys(indiaLocations[state]).sort();
};


export const getBlocks = (state, district) => {
  if (
    !state ||
    !district ||
    !indiaLocations[state] ||
    !indiaLocations[state][district]
  ) {
    return [];
  }

  return Object.keys(indiaLocations[state][district]).sort();
};


export const getVillages = (state, district, block) => {
  if (
    !state ||
    !district ||
    !block ||
    !indiaLocations[state] ||
    !indiaLocations[state][district] ||
    !indiaLocations[state][district][block]
  ) {
    return [];
  }

  return indiaLocations[state][district][block];
};


